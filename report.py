"""
PDF report generator for Zephyr code review findings.
"""

from reportlab.lib.pagesizes import A4
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable, Table, TableStyle
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.lib import colors
import datetime

NAVY  = colors.HexColor("#1F3A5F")
RED   = colors.HexColor("#C0392B")
ORANGE= colors.HexColor("#E67E22")
BLUE  = colors.HexColor("#2980B9")
DARK  = colors.HexColor("#1A1A1A")
GRAY  = colors.HexColor("#555555")
LIGHT = colors.HexColor("#F4F6F8")

SEVERITY_COLOR = {
    "CRITICAL": RED,
    "WARNING":  ORANGE,
    "INFO":     BLUE,
}

h1    = ParagraphStyle("h1",    fontName="Helvetica-Bold", fontSize=16, leading=20, textColor=NAVY)
h2    = ParagraphStyle("h2",    fontName="Helvetica-Bold", fontSize=11, leading=14, textColor=NAVY, spaceBefore=8)
body  = ParagraphStyle("body",  fontName="Helvetica",      fontSize=9,  leading=13, textColor=DARK)
small = ParagraphStyle("small", fontName="Helvetica",      fontSize=8,  leading=11, textColor=GRAY)
code  = ParagraphStyle("code",  fontName="Courier",        fontSize=8,  leading=11, textColor=DARK, backColor=LIGHT)

def severity_badge(sev):
    c = SEVERITY_COLOR.get(sev, BLUE)
    return Paragraph(f'<font color="#{c.hexval()[2:]}"><b>[{sev}]</b></font>', body)

def rule():
    return HRFlowable(width="100%", thickness=0.5, color=NAVY, spaceBefore=2, spaceAfter=4)

def generate_report(filename, source_file, findings, source_lines):
    doc = SimpleDocTemplate(filename, pagesize=A4,
        leftMargin=18*mm, rightMargin=18*mm, topMargin=15*mm, bottomMargin=15*mm)

    elements = []

    # Title
    elements.append(Paragraph("Zephyr C Code Review Report", h1))
    elements.append(HRFlowable(width="100%", thickness=2, color=NAVY, spaceBefore=3, spaceAfter=6))
    elements.append(Paragraph(f"File: <b>{source_file}</b>", body))
    elements.append(Paragraph(f"Date: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M')}", small))
    elements.append(Paragraph(f"Total lines: {len(source_lines)}", small))
    elements.append(Spacer(1, 4*mm))

    # Summary table
    n_crit = sum(1 for f in findings if f["severity"] == "CRITICAL")
    n_warn = sum(1 for f in findings if f["severity"] == "WARNING")
    n_info = sum(1 for f in findings if f["severity"] == "INFO")

    elements.append(Paragraph("Summary", h2))
    elements.append(rule())

    summary_data = [
        [Paragraph("<b>Severity</b>", body), Paragraph("<b>Count</b>", body)],
        [Paragraph('<font color="#C0392B"><b>CRITICAL</b></font>', body), Paragraph(str(n_crit), body)],
        [Paragraph('<font color="#E67E22"><b>WARNING</b></font>',  body), Paragraph(str(n_warn), body)],
        [Paragraph('<font color="#2980B9"><b>INFO</b></font>',     body), Paragraph(str(n_info), body)],
        [Paragraph("<b>TOTAL</b>", body), Paragraph(f"<b>{len(findings)}</b>", body)],
    ]
    t = Table(summary_data, colWidths=[60*mm, 30*mm])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), NAVY),
        ('TEXTCOLOR',  (0,0), (-1,0), colors.white),
        ('ROWBACKGROUNDS', (0,1), (-1,-1), [LIGHT, colors.white]),
        ('GRID', (0,0), (-1,-1), 0.3, colors.grey),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('TOPPADDING', (0,0), (-1,-1), 4),
        ('BOTTOMPADDING', (0,0), (-1,-1), 4),
    ]))
    elements.append(t)
    elements.append(Spacer(1, 6*mm))

    # Findings
    elements.append(Paragraph("Findings", h2))
    elements.append(rule())

    if not findings:
        elements.append(Paragraph("No issues found.", body))
    else:
        for f in sorted(findings, key=lambda x: (
            0 if x["severity"]=="CRITICAL" else 1 if x["severity"]=="WARNING" else 2, x["line"])):

            sev_color = SEVERITY_COLOR.get(f["severity"], BLUE)
            hex_color = sev_color.hexval()[2:]

            elements.append(Paragraph(
                f'<font color="#{hex_color}"><b>[{f["severity"]}]</b></font>  '
                f'Line {f["line"]} — <b>{f["rule"]}</b>', body))
            elements.append(Paragraph(f["message"], small))

            # Show the actual line of code
            line_idx = f["line"] - 1
            if 0 <= line_idx < len(source_lines):
                snippet = source_lines[line_idx].rstrip()
                elements.append(Paragraph(f"{f['line']:>4}:  {snippet}", code))

            elements.append(Spacer(1, 3*mm))

    # Footer
    elements.append(Spacer(1, 6*mm))
    elements.append(HRFlowable(width="100%", thickness=0.5, color=GRAY))
    elements.append(Paragraph(
        "Generated by Zephyr Code Reviewer — github.com/mehdiouazzani", small))

    doc.build(elements)
